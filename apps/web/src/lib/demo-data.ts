/**
 * Retourne les données de fallback pour un indicateur IMF
 * en filtrant sur les périodes demandées.
 */
export function getImfFallback(
  indicator: string,
  periods: string[],
): ImfFallbackData {
  const resolvedIndicator = INDICATOR_ALIASES[indicator] ?? indicator;
  const rawValues = INDICATOR_MAP[resolvedIndicator] ?? {};

  const values: Record<string, Record<string, number>> = {};
  for (const [iso3, yearMap] of Object.entries(rawValues)) {
    const filtered: Record<string, number> = {};
    for (const p of periods) {
      if (yearMap[p] !== undefined) filtered[p] = yearMap[p];
    }
    if (Object.keys(filtered).length > 0) values[iso3] = filtered;
  }

  return {
    indicator: resolvedIndicator,
    periods,
    values,
    isFallback: true,
  };
}

export { YEARS_10, YEARS_5, YEARS_3 };
